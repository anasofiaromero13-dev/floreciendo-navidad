import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const context={people:[{uuid:'child',name:'Sara'}],esc:s=>String(s??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]))};
vm.createContext(context);
vm.runInContext(fs.readFileSync(new URL('../src/questions.js',import.meta.url),'utf8'),context);
const questions=[{id:'one',child_id:'child',sponsor_id:'owner',question:'¿Talla de pantalón? <script>alert(1)</script>',answer:null,created_at:'2026-11-08T12:00:00Z'},{id:'two',child_id:'other',sponsor_id:'owner',question:'Otra carta',created_at:'2026-11-08T12:00:00Z'}];
let html=context.sponsorQuestionSection('child',questions,true);
assert.match(html,/Pendiente de respuesta/);
assert.match(html,/Enviar pregunta/);
assert.match(html,/No enviamos avisos por correo/);
assert.ok(!html.includes('Otra carta'));
assert.ok(!html.includes('<script>'));
html=context.sponsorQuestionSection('child',[{...questions[0],answer:'Talla 14 para ambas prendas.',answered_at:'2026-11-08T13:00:00Z'}],false);
assert.match(html,/Talla 14 para ambas prendas/);
assert.ok(!html.includes('Enviar pregunta'));
const inbox=context.staffQuestionSection([questions[0]],[{user_id:'owner',full_name:'Padrino QA'}]);
assert.match(inbox,/1 por responder/);
assert.match(inbox,/Padrino QA/);
assert.match(inbox,/Enviar respuesta/);
assert.ok(!inbox.includes('<script>'));
console.log('Preguntas verificadas: historial, estados, formularios y texto escapado.');
